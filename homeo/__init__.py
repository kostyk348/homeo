"""
homeo — гомеостатический контроллер на инвариантах.

Порт ядра с C++ (CIDHC, /include/homeo/). Идея: поведение агента
определяется КОНКУРИРУЮЩИМИ инвариантами I_j(X) в пространстве политики X
(каждая координата — управляющий коэффициент, нормализован к [−1, 1]):

    E(X) = Σ_j w_j(X) · |I_j(X)|^p_j

где w_j(X) — вес инварианта, который МОЖЕТ ЗАВИСЕТЬ ОТ СОСТОЯНИЯ/САМОГО X
(аналитическая функция: sigmoid/clamp/кусочные/степенные — никакой нейронки).

Минимизация E — градиентным спуском (Adam) + термальный шум CLT (12·U−6)
с annealing T_t = T0·2^(−k·t), как в relaxer.hpp. Численный градиент через
центральные разности АВТОМАТИЧЕСКИ учитывает dW/dX (само-вес).

Один тик (`tick()`) = один проход релаксации до сходимости. Контроллер
не хранит "правильное" поведение — он каждый тик пере-балансирует инварианты
под текущее состояние среды и возвращает развёрнутые коэффициенты политики.

Быстрое применение: см. examples/, тесты — tests/.
"""

